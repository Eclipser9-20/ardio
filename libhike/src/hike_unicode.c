/* UTF-8 decoding and encoding, and how many columns a character occupies.
 *
 * The decoder rejects rather than repairs. That is a security position as much
 * as a tidiness one: a decoder that quietly turns an overlong encoding into
 * the character it was pretending to be lets a caller validate one string and
 * display another, and a decoder that accepts a truncated sequence at the end
 * of a buffer reads past it. So every one of the classic bad cases -- overlong
 * forms, the UTF-16 surrogate range, values above U+10FFFF, continuation bytes
 * that are not continuations, and sequences cut short by the end of the input
 * -- returns 0 here, and the caller decides what to do about it.
 *
 * The width tables reflect Unicode 15.1. They are the standard interval sets:
 * zero width for the combining marks (general categories Mn, Me and Cf, plus
 * the Hangul conjoining jamo that compose onto a preceding syllable), and two
 * columns for the East Asian Wide and Fullwidth ranges plus the emoji blocks
 * terminals actually render double width.
 *
 * What that means for newer code points is worth being explicit about, because
 * it is the failure mode you will meet in practice: a character assigned after
 * Unicode 15.1 that falls outside these intervals is reported as one column.
 * If a terminal draws it in two, the rest of that row is off by one until the
 * next present repaints it. The tables are intervals rather than a database
 * because pulling in the full UCD to be right about characters that most fonts
 * cannot draw is a poor trade; the ranges below are deliberately written as
 * whole blocks where a block was allocated wide, so future assignments inside
 * an already-wide block come out right without a table update.
 */

