static bool in_ranges(const hike_range* table, size_t n, uint32_t cp) {
    /* Binary search: the tables are sorted and non-overlapping by
     * construction, and width is asked once per character per frame. */
    size_t lo = 0, hi = n;
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2;
        if (cp < table[mid].lo) hi = mid;
        else if (cp > table[mid].hi) lo = mid + 1;
        else return true;
    }
    return false;
}

size_t hike_utf8_decode(const char* utf8, size_t len, uint32_t* out) {
    if (utf8 == NULL || len == 0) return 0;

    const unsigned char* p = (const unsigned char*)utf8;
    unsigned char b0 = p[0];
    uint32_t cp;
    size_t need;

    if (b0 < 0x80) {
        if (out) *out = b0;
        return 1;
    } else if ((b0 & 0xE0) == 0xC0) {
        cp = b0 & 0x1Fu; need = 2;
    } else if ((b0 & 0xF0) == 0xE0) {
        cp = b0 & 0x0Fu; need = 3;
    } else if ((b0 & 0xF8) == 0xF0) {
        cp = b0 & 0x07u; need = 4;
    } else {
        /* A bare continuation byte, or one of the 5- and 6-byte lead bytes
         * that UTF-8 has not permitted since it was restricted to U+10FFFF. */
        return 0;
    }

    if (len < need) return 0; /* Truncated. Reported, never guessed at. */

    for (size_t i = 1; i < need; ++i) {
        if ((p[i] & 0xC0) != 0x80) return 0;
        cp = (cp << 6) | (uint32_t)(p[i] & 0x3Fu);
    }

    /* Overlong forms encode a small value in more bytes than it needs. They
     * decode to a perfectly ordinary character, which is exactly why they are
     * dangerous: they let the same character have several spellings and slip
     * past any check made on the bytes. */
    if (need == 2 && cp < 0x80) return 0;
    if (need == 3 && cp < 0x800) return 0;
    if (need == 4 && cp < 0x10000) return 0;

    /* The surrogate range exists only to let UTF-16 address the supplementary
     * planes. It is not a scalar value and has no UTF-8 encoding. */
    if (cp >= 0xD800 && cp <= 0xDFFF) return 0;
    if (cp > 0x10FFFF) return 0;

    if (out) *out = cp;
    return need;
}

size_t hike_utf8_encode(uint32_t codepoint, char out[4]) {
    if (out == NULL) return 0;
    if (codepoint > 0x10FFFF) return 0;
    if (codepoint >= 0xD800 && codepoint <= 0xDFFF) return 0;

    if (codepoint < 0x80) {
        out[0] = (char)codepoint;
        return 1;
    }
    if (codepoint < 0x800) {
        out[0] = (char)(0xC0u | (codepoint >> 6));
        out[1] = (char)(0x80u | (codepoint & 0x3Fu));
        return 2;
    }
    if (codepoint < 0x10000) {
        out[0] = (char)(0xE0u | (codepoint >> 12));
        out[1] = (char)(0x80u | ((codepoint >> 6) & 0x3Fu));
        out[2] = (char)(0x80u | (codepoint & 0x3Fu));
        return 3;
    }
    out[0] = (char)(0xF0u | (codepoint >> 18));
    out[1] = (char)(0x80u | ((codepoint >> 12) & 0x3Fu));
    out[2] = (char)(0x80u | ((codepoint >> 6) & 0x3Fu));
    out[3] = (char)(0x80u | (codepoint & 0x3Fu));
    return 4;
}

int hike_char_width(uint32_t codepoint) {
    /* NUL takes no space, and the C0/C1 control characters have no width the
     * grid can express -- they are not printable, so treating them as one
     * column would reserve a cell for something that draws nothing. */
    if (codepoint == 0) return 0;
    if (codepoint < 32 || (codepoint >= 0x7F && codepoint < 0xA0)) return 0;

    if (in_ranges(k_zero_width,
                  sizeof k_zero_width / sizeof k_zero_width[0], codepoint))
        return 0;
    if (in_ranges(k_wide, sizeof k_wide / sizeof k_wide[0], codepoint))
        return 2;
    return 1;
}

int hike_text_width(const char* utf8) {
    if (utf8 == NULL) return 0;

    /* The length is measured once and carried, so a sequence truncated by the
     * end of the string is rejected as truncated rather than read past. */
    size_t len = 0;
    while (utf8[len] != '\0') ++len;

    int columns = 0;
    size_t i = 0;
    while (i < len) {
        const char* p = utf8 + i;
        uint32_t cp = 0;
        size_t used = hike_utf8_decode(p, len - i, &cp);
        if (used == 0) {
            /* Invalid input still has to be given a width, because the caller
             * will draw something for it. One column, matching the single
             * replacement character hike_text substitutes for the same byte. */
            columns += 1;
            i += 1;
            continue;
        }
        columns += hike_char_width(cp);
        i += used;
    }
    return columns;
}
